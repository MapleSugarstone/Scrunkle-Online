// Converts the extracted source project into TypeScript modules under src/game/generated.
// Usage: npx tsx tools/transpile/main.ts
import fs from 'node:fs';
import path from 'node:path';
import { parseProject, sanitize } from './ir.ts';
import { analyze, SpriteGen } from './gen.ts';
import { applyOverrides, readOverrides } from '../lib/lists.ts';
import { SAVE_LISTS } from '../../src/game/saves.ts';

const ROOT = path.resolve(import.meta.dirname, '../..');
const project = JSON.parse(fs.readFileSync(path.join(ROOT, 'sb3/project.json'), 'utf8'));
const overrides = readOverrides(project);
applyOverrides(project, overrides);
for (const o of overrides) console.log(`[lists] ${o.list} (${o.target}): ${o.items.length} items from ${o.file}`);
const meta = JSON.parse(fs.readFileSync(path.join(ROOT, 'out/ref-meta.json'), 'utf8'));
const outDir = path.join(ROOT, 'src/game/generated');
fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

const targets = parseProject(project);
const stage = targets.find((t) => t.isStage)!;

// Lists some block writes, by id. The page also writes the saved lists, so those count as written too.
const LIST_WRITES = new Set(['data_addtolist', 'data_deleteoflist', 'data_deletealloflist', 'data_insertatlist', 'data_replaceitemoflist']);
const writtenLists = new Set<string>();
for (const t of project.targets) {
  for (const b of Object.values(t.blocks) as any[]) if (b && LIST_WRITES.has(b.opcode) && b.fields?.LIST) writtenLists.add(b.fields.LIST[1]);
}
for (const name of SAVE_LISTS) {
  const decl = stage.lists.find((l) => l.name === name);
  if (decl) writtenLists.add(decl.id);
}
const usedFiles = new Set<string>(['index', 'Stage_']);
const files: string[] = [];
let errors = 0;

for (const t of targets) {
  const an = analyze(t);
  for (const w of an.warnings) console.warn(`[warn] ${w}`);
  const gen = new SpriteGen(t, stage, an);
  gen.fixedLists = t.lists.filter((l) => !writtenLists.has(l.id)).map((l) => l.prop);
  const code = gen.generate();
  for (const e of gen.errors) {
    console.error(`[error] ${t.name}: ${e}`);
    errors++;
  }
  const file = t.isStage ? 'Stage_' : sanitize(t.name, usedFiles, 'Sprite');
  files.push(file);
  fs.writeFileSync(path.join(outDir, `${file}.ts`), code);
  const units = (code.match(/rt\.unit\(/g) ?? []).length;
  const plains = (code.match(/\n {2}function /g) ?? []).length;
  console.log(`${t.name.padEnd(22)} -> ${file}.ts  scripts=${t.scripts.length} procs=${t.procs.size} units=${units} functions=${plains} lines=${code.split('\n').length}`);
}

// List monitors that blocks can show or hide.
const monitors = (project.monitors ?? [])
  .filter((m: any) => m.mode === 'list' && m.spriteName === null)
  .map((m: any) => {
    const decl = stage.lists.find((l) => l.name === m.params.LIST);
    return decl ? { prop: decl.prop, label: m.params.LIST, x: m.x, y: m.y, width: m.width, height: m.height, visible: !!m.visible } : null;
  })
  .filter(Boolean);

// Stage variable monitors; the page draws the ones that are shown.
const varMonitors = (project.monitors ?? [])
  .filter((m: any) => m.opcode === 'data_variable' && m.spriteName === null)
  .map((m: any) => {
    const decl = stage.vars.find((v) => v.name === m.params.VARIABLE);
    return decl ? { prop: decl.prop, label: m.params.VARIABLE, mode: m.mode, x: m.x, y: m.y, visible: !!m.visible } : null;
  })
  .filter(Boolean);

// The graphic effects that blocks set or change, so the page can compile their shaders before play.
const effects = new Set<string>();
for (const t of project.targets) {
  for (const b of Object.values(t.blocks) as any[]) {
    if (b && (b.opcode === 'looks_seteffectto' || b.opcode === 'looks_changeeffectby')) effects.add(String(b.fields.EFFECT[0]).toLowerCase());
  }
}

fs.writeFileSync(
  path.join(outDir, 'index.ts'),
  `// Generated by tools/transpile. Modules in the source project's target order.
import type { SpriteModule } from '../../engine/runtime.ts';
import type { Monitors } from '../../engine/defs.ts';
${files.map((f, i) => `import * as m${i} from './${f}.ts';`).join('\n')}

export const modules: SpriteModule[] = [${files.map((_, i) => `m${i}`).join(', ')}];

export const monitors: Monitors = { lists: ${JSON.stringify(monitors)}, vars: ${JSON.stringify(varMonitors)} };

/** The graphic effects the project's blocks set or change. */
export const effectsUsed: string[] = ${JSON.stringify([...effects].sort())};
`,
);

// Costume, skin and sound tables from the reference renderer's measurements.
const skins: unknown[] = [];
const costumes: unknown[][] = [];
const sounds: unknown[][] = [];
for (const t of targets) {
  const m = meta.find((x: any) => x.name === t.name && x.isStage === t.isStage);
  if (!m) throw new Error(`no metadata for ${t.name}`);
  costumes.push(
    m.costumes.map((c: any) => {
      const isSvg = c.format === 'svg';
      skins.push({
        w: c.size[0],
        h: c.size[1],
        rcx: c.skinRotationCenter[0],
        rcy: c.skinRotationCenter[1],
        kind: isSvg ? 'svg' : 'bitmap',
        file: `costumes/${c.md5ext}`,
        res: isSvg ? 1 : c.bitmapResolution || 2,
        maxScale: isSvg ? c.maxTextureScale : 1,
      });
      return { name: c.name, skin: skins.length - 1 };
    }),
  );
  sounds.push(
    t.json.sounds.map((s: any) => ({ name: s.name, file: `sounds/${s.md5ext}`, rate: s.rate, sampleCount: s.sampleCount })),
  );
}
fs.writeFileSync(path.join(ROOT, 'src/game/assets-data.json'), JSON.stringify({ skins, costumes, sounds }));
console.log(`skins=${skins.length} errors=${errors}`);
if (errors) process.exitCode = 1;
